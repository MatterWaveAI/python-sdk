"""MatterWave's Python client: the OpenAI-compatible `/v1` surface, typed.

    from matterwave_sdk import MatterWave

    client = MatterWave(api_key="mw_...", base_url="https://your-matterwave.example")
    print(client.chat.completions.create(messages=[{"role": "user", "content": "hi"}]).content)

Both arguments default to `MATTERWAVE_API_KEY` and `MATTERWAVE_BASE_URL`.

`client.conversations` is the app's own conversation API, streaming typed
frames (`matterwave_sdk.frames`); `client.auth.device` signs a person in by
device code and returns the key to use. `client.keys`, `client.usage`,
`client.webhooks`, `client.attachments`, `client.library`,
`client.notifications`, `client.announcements`, `client.entitlements` and
`client.shares` are the app's native routes for the same, `client.admin`
is the operator surface (the platform `admin` role, not an API key's), and
`client.mcp` speaks the `/mcp` JSON-RPC endpoint (list tools, call one,
send a message). The account families sit beside them: `client.account`
(self-service: sessions, preferences, password, email change, terms,
deletion), `client.exports`/`client.imports` (data jobs), `client.members`
(people, invites, links, join), `client.org` (the org, its model
allow-list, sharing, SSO/domains/IdP, MFA policy), `client.billing`
(plans, checkout, invoices), `client.passkeys`, `client.mfa`,
`client.accounts` (browser account switching), `client.speech`
(transcription) and `client.sync` (edge pairing and push).
`matterwave_sdk.agent` is the agent tool contract the coding clients
share, with its path, edit, diff and approval helpers.
"""

