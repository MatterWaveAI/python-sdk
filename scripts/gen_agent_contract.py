"""Generate the TypeScript SDK's copy of the agent contract, or check it.

    python scripts/gen_agent_contract.py                      # writes ../typescript-sdk
    python scripts/gen_agent_contract.py --ts-sdk PATH
    python scripts/gen_agent_contract.py --check [--ts-sdk PATH]

The contract's one source is src/matterwave_sdk/agent/contract.json in this
repo. This writes two files into the TypeScript SDK checkout:

- src/agent/contract.ts: the contract as a typed `as const` literal, with
  its SHA-256 over the canonical JSON (compact separators, keys in file
  order, non-ASCII kept), which the TypeScript suite recomputes so a hand
  edit of the copy fails there too;
- tests/agent-conformance.json: the conformance cases both suites run,
  copied byte for byte from tests/agent_conformance.json.

`--check` writes nothing and exits 1, naming the files, when either copy is
not what this would write: the drift check CI runs with both repos side by
side.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path
from typing import Any

REPO = Path(__file__).resolve().parents[1]
CONTRACT = REPO / "src" / "matterwave_sdk" / "agent" / "contract.json"
CONFORMANCE = REPO / "tests" / "agent_conformance.json"
DEFAULT_TS_SDK = REPO.parent / "typescript-sdk"
TS_CONTRACT = Path("src") / "agent" / "contract.ts"
TS_CONFORMANCE = Path("tests") / "agent-conformance.json"


def canonical(contract: Any) -> str:
    """The form both languages hash: `JSON.stringify` of the TypeScript
    literal spells the same characters."""
    return json.dumps(contract, separators=(",", ":"), ensure_ascii=False)


def digest(contract: Any) -> str:
    return hashlib.sha256(canonical(contract).encode("utf-8")).hexdigest()


def render_contract_ts(contract: Any) -> str:
    body = json.dumps(contract, indent=2, ensure_ascii=False)
    return (
        "// Generated by the Python SDK's scripts/gen_agent_contract.py from\n"
        "// src/matterwave_sdk/agent/contract.json, the contract's one source.\n"
        "// Do not edit: change the JSON there and regenerate.\n"
        "\n"
        "/** SHA-256 of the contract's canonical JSON; tests/agent-contract.test.ts recomputes it. */\n"
        f'export const CONTRACT_SHA256 = "{digest(contract)}";\n'
        "\n"
        "/** The agent tool contract, as decoded from contract.json. */\n"
        f"export const CONTRACT = {body} as const;\n"
    )


def outputs() -> dict[Path, bytes]:
    contract = json.loads(CONTRACT.read_text(encoding="utf-8"))
    return {
        TS_CONTRACT: render_contract_ts(contract).encode("utf-8"),
        TS_CONFORMANCE: CONFORMANCE.read_bytes(),
    }


def stale(ts_sdk: Path) -> list[Path]:
    """The generated files under `ts_sdk` that differ from what this writes."""
    return [
        relative
        for relative, content in outputs().items()
        if not (ts_sdk / relative).exists() or (ts_sdk / relative).read_bytes() != content
    ]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--ts-sdk", type=Path, default=DEFAULT_TS_SDK, help="TypeScript SDK checkout"
    )
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 on drift")
    args = parser.parse_args(argv)
    ts_sdk: Path = args.ts_sdk
    if not (ts_sdk / "package.json").exists():
        print(f"{ts_sdk} is not the TypeScript SDK checkout (no package.json)")
        return 2
    if args.check:
        drifted = stale(ts_sdk)
        for relative in drifted:
            print(f"{ts_sdk / relative} is out of date; run scripts/gen_agent_contract.py")
        if not drifted:
            print("the TypeScript SDK's agent contract matches contract.json")
        return 1 if drifted else 0
    for relative, content in outputs().items():
        target = ts_sdk / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(content)
        print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
